#[derive(Clone, Copy, PartialEq, Eq, Hash, Debug)]
pub struct CodeInfo {
    pub code: &'static str,
    pub title: &'static str,
}

const fn code(code: &'static str, title: &'static str) -> CodeInfo {
    CodeInfo { code, title }
}

